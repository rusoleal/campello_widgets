#!/bin/bash
# Embeds the WGSL widget shaders (shaders/webgpu/*.wgsl, hand-written ports
# of shaders/vulkan/) into src/shaders/webgpu_widgets.h for the web build.
# Rebuild after editing a .wgsl file: ./build_webgpu_shaders.sh
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHADER_DIR="$SCRIPT_DIR/shaders/webgpu"
OUT_HEADER="$SCRIPT_DIR/src/shaders/webgpu_widgets.h"

mkdir -p "$SCRIPT_DIR/src/shaders"

python3 - "$OUT_HEADER" "$SHADER_DIR"/*.wgsl <<'PYEOF'
import os
import sys

out_path = sys.argv[1]
parts = []
for path in sorted(sys.argv[2:]):
    # rect.vert.wgsl -> krect_vert_wgsl
    name = os.path.basename(path).replace(".", "_")
    source = open(path).read()
    if ")WGSL\"" in source:
        sys.exit(f"{path}: contains the raw-string delimiter")
    parts.append(f'static const char k{name}[] = R"WGSL(\n{source})WGSL";\n')

header = """#pragma once

// Auto-generated by build_webgpu_shaders.sh — do not edit.
// Rebuild with: ./build_webgpu_shaders.sh

namespace systems::leal::campello_widgets::shaders {

""" + "\n".join(parts) + """
} // namespace systems::leal::campello_widgets::shaders
"""
open(out_path, "w").write(header)
print(f"Wrote {out_path} ({len(parts)} shaders)")
PYEOF
